const {chromium}=require('playwright');
const fs=require('node:fs/promises');
const path=require('node:path');
const assert=require('node:assert/strict');
const base='http://127.0.0.1:8896', root=path.resolve(__dirname,'../data/password-browser');
const password='a secure password 12345';
(async()=>{
 const browser=await chromium.launch({headless:true}), errors=[], checks=[];
 let context=await browser.newContext({viewport:{width:1280,height:900}}), page=await context.newPage();
 page.on('pageerror',e=>errors.push(e.message));
 try {
  await page.goto(base); await page.locator('#account-button').click();
  await page.getByRole('button',{name:'パスワードの設定・再設定',exact:true}).click();
  await page.locator('#password-request-form [name=email]').fill('existing@example.test');
  await page.locator('#password-request-form button[type=submit]').click();
  await page.locator('#password-request-status').filter({hasText:'お送りしました'}).waitFor();
  let inbox=JSON.parse(await fs.readFile(path.join(root,'inbox.json'),'utf8'));
  const token=inbox.text.match(/#token=(\S+)/)[1];
  await page.goto(base+'/password#token='+token);
  await page.locator('#password-complete-form').waitFor(); assert.equal(page.url(),base+'/password');
  assert.equal((await context.request.get(base+'/api/service/me')).status(),401);
  await page.locator('[name=password]').fill(password); await page.locator('[name=confirmation]').fill(password);
  await page.locator('#password-complete-form button').click();
  await page.getByRole('heading',{name:'パスワードを設定しました'}).waitFor();
  await page.locator('#password-login').click(); await page.locator('#login-form [name=email]').fill('existing@example.test');
  await page.locator('#login-form [name=password]').fill(password); await page.locator('#login-form button').click();
  await page.locator('#auth-dialog').waitFor({state:'hidden'});
  assert.equal((await(await context.request.get(base+'/api/service/me')).json()).user.email,'existing@example.test');
  checks.push('Existing account sets password from one-use mail link; GET does not log in or consume token');
  await page.screenshot({path:path.join(root,'desktop.png'),fullPage:true});
  const storage=await context.storageState(); await context.close();
  context=await browser.newContext({storageState:storage,viewport:{width:390,height:844}}); page=await context.newPage();
  page.on('pageerror',e=>errors.push(e.message)); await page.goto(base+'/workspace');
  await page.locator('[data-action=logout]').waitFor();
  assert.equal((await context.request.get(base+'/api/service/me')).status(),200);
  checks.push('Persistent cookie restores login in a fresh browser context');
  await page.screenshot({path:path.join(root,'mobile.png'),fullPage:true});
  await page.locator('[data-action=logout]').click(); await page.waitForFunction(()=>document.querySelector('#account-button').textContent==='ログイン');
  assert.equal((await context.request.get(base+'/api/service/me')).status(),401);
  checks.push('Logout revokes the stored session');
  await page.locator('#account-button').click(); await page.getByRole('button',{name:'新規登録',exact:true}).click();
  const newEmail='new-browser-'+Date.now()+'@example.test';
  await page.locator('#auth-form [name=email]').fill(newEmail); await page.locator('#auth-form [name=name]').fill('新規利用者');
  await page.locator('#auth-form [name=consent]').check(); await page.locator('#auth-form button').click(); await page.locator('#code-form').waitFor();
  inbox=JSON.parse(await fs.readFile(path.join(root,'inbox.json'),'utf8'));
  await page.locator('#code-form [name=code]').fill(inbox.code); await page.locator('#code-form [name=password]').fill(password); await page.locator('#code-form [name=confirmation]').fill(password);
  await page.locator('#code-form button').click(); await page.locator('#auth-dialog').waitFor({state:'hidden'});
  assert.equal((await(await context.request.get(base+'/api/service/me')).json()).user.email,newEmail);
  checks.push('New registration confirms email and sets a password');
  await page.locator('[data-action=logout]').click(); await page.waitForFunction(()=>document.querySelector('#account-button').textContent==='ログイン');
  await page.locator('#account-button').click(); await page.locator('#login-form [name=email]').fill('shumpei.hasegawa@maora.co.jp'); await page.locator('#login-form [name=password]').fill(password);
  await page.screenshot({path:path.join(root,'login-mobile.png'),fullPage:true});
  await page.locator('#login-form button').click(); await page.locator('#auth-dialog').waitFor({state:'hidden'}); await page.goto(base+'/admin/intakes');
  await page.locator('#send-password-invitations').click(); await page.getByRole('button',{name:'設定案内の送信処理が完了しました'}).waitFor();
  assert.ok((await page.locator('#password-invitation-status').textContent()).includes('未送信：0人'));
  inbox=JSON.parse(await fs.readFile(path.join(root,'inbox.json'),'utf8')); assert.deepEqual(inbox.to,['invitee@example.test']);
  checks.push('Operator sends account setup notices through authenticated UI without exposing provider keys');
  assert.deepEqual(errors,[]); console.log(JSON.stringify({passed:true,checks,errors}));
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
